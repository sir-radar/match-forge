import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { ResolutionDecisionForm } from "@/components/resolution-decision";
const key = "team:00000000-0000-4000-8000-000000000001";
afterEach(() => vi.unstubAllGlobals());
it("requires exact preview, owner credential and explicit approval; retries reuse identity", async () => {
  const calls: RequestInit[] = [];
  const fetch = vi.fn(async (_url: string, options: RequestInit) => {
    calls.push(options);
    const body = JSON.parse(String(options.body));
    if (String(_url).endsWith("preview")) return new Response(JSON.stringify({ ...body, detail: { case_key: key }, allowed: true, qualification: { status: "QUALIFIED", reason: "RECHECK_ONLY" }, evidence_version: "a".repeat(64) }));
    if (calls.filter((call) => String(call.body).includes('"approved":true')).length === 1) return new Response(JSON.stringify({ error: "outcome unknown" }), { status: 503 });
    return new Response(JSON.stringify({ ...body, detail: { result: { status: "RECORDED" } } }));
  });
  vi.stubGlobal("fetch", fetch);
  const onApplied = vi.fn();
  render(<ResolutionDecisionForm caseKey={key} data={{}} onApplied={onApplied} />);
  expect(screen.queryByLabelText("Owner credential")).not.toBeInTheDocument();
  fireEvent.change(screen.getByLabelText("Reason"), { target: { value: "Check retained proof" } });
  fireEvent.click(screen.getByRole("button", { name: "Preview impact and evidence" }));
  const apply = await screen.findByRole("button", { name: "Approve and apply decision" });
  expect(apply).toBeDisabled();
  fireEvent.change(screen.getByLabelText("Owner credential"), { target: { value: "owner-secret" } });
  fireEvent.click(screen.getByRole("checkbox"));
  fireEvent.click(apply); fireEvent.click(apply);
  expect(await screen.findByRole("alert")).toHaveTextContent("outcome unknown");
  expect(fetch).toHaveBeenCalledTimes(2);
  fireEvent.click(screen.getByRole("checkbox")); fireEvent.click(apply);
  await waitFor(() => expect(onApplied).toHaveBeenCalledTimes(1));
  expect(JSON.parse(String(calls[1].body)).request_id).toBe(JSON.parse(String(calls[2].body)).request_id);
  expect(calls[1].headers).toMatchObject({ Authorization: "Bearer owner-secret" });
  expect(calls[1].body).not.toContain("owner-secret");
  expect(screen.getByLabelText("Owner credential")).toHaveValue("");
});
it("invalidates a preview when the reason changes", async () => {
  vi.stubGlobal("fetch", vi.fn(async (_url: string, options: RequestInit) => new Response(JSON.stringify({ ...JSON.parse(String(options.body)), detail: { case_key: key }, allowed: false, qualification: { status: "BLOCKED", reason: "MISSING_PROOF" }, evidence_version: "a".repeat(64) }))));
  render(<ResolutionDecisionForm caseKey={key} data={{}} onApplied={vi.fn()} />);
  fireEvent.change(screen.getByLabelText("Reason"), { target: { value: "Initial review" } });
  fireEvent.click(screen.getByRole("button", { name: "Preview impact and evidence" }));
  expect(await screen.findByRole("button", { name: "Approve and apply decision" })).toBeDisabled();
  fireEvent.change(screen.getByLabelText("Reason"), { target: { value: "Changed review" } });
  expect(screen.queryByLabelText("Owner credential")).not.toBeInTheDocument();
});
it("binds a correction to retained target and fixture IDs", async () => {
  const target = "00000000-0000-4000-8000-000000000002";
  const fetch = vi.fn(async (_url: string, options: RequestInit) => new Response(JSON.stringify({ ...JSON.parse(String(options.body)), detail: { case_key: key }, allowed: true, qualification: { status: "QUALIFIED", reason: "RETAINED" }, evidence_version: "a".repeat(64) })));
  vi.stubGlobal("fetch", fetch);
  render(<ResolutionDecisionForm caseKey={key} data={{ candidates: [{ mapping_id: target, name: "Target", provider: "retained" }], correction_options: [{ original_decision_id: "prior", fixture_registration_id: "registration", orientation: "HOME", fixture_id: "fixture" }] }} onApplied={vi.fn()} />);
  fireEvent.change(screen.getByLabelText("Action"), { target: { value: "CORRECT" } });
  fireEvent.change(screen.getByLabelText("Target mapping"), { target: { value: target } });
  fireEvent.change(screen.getByLabelText("Retained contradiction"), { target: { value: "prior" } });
  fireEvent.change(screen.getByLabelText("Reason"), { target: { value: "Exact retained correction" } });
  fireEvent.click(screen.getByRole("button", { name: "Preview impact and evidence" }));
  await screen.findByLabelText("Owner credential");
  expect(JSON.parse(String(fetch.mock.calls[0][1].body)).candidate).toEqual({ target_mapping_id: target, original_decision_id: "prior", fixture_registration_id: "registration", orientation: "HOME" });
  fireEvent.change(screen.getByLabelText("Action"), { target: { value: "REJECT" } });
  expect(screen.queryByLabelText("Owner credential")).not.toBeInTheDocument();
  expect(screen.queryByLabelText("Retained contradiction")).not.toBeInTheDocument();
});
